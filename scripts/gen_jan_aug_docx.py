def add_table(headers, rows, widths=None, hdr_fill='4472C4', hdr_color=(255,255,255)):
    t=doc.add_table(rows=1, cols=len(headers)); t.alignment=WD_TABLE_ALIGNMENT.CENTER
    t.style='Table Grid'
    for i,h in enumerate(headers):
        set_cell(t.rows[0].cells[i], h, bold=True, color=hdr_color, align='center', size=10)
        shade(t.rows[0].cells[i], hdr_fill)
    for ri,row in enumerate(rows):
        cells=t.add_row().cells
        for i,v in enumerate(row):
            al='center' if i in (0,5,6) else ('right' if i in (2,3,4) else 'left')
            # 默认对齐：数字右、首列居中
            is_num = isinstance(v,(int,float)) or (isinstance(v,str) and v.replace(',','').replace('.','').replace('-','').replace('%','').isdigit())

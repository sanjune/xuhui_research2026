"""企业名称归并 —— 全站唯一口径源。

背景
----
上海中誉物业管理有限公司于 2026 年 8 月完成企业名称变更，更名为
**上海中誉城市运营服务有限公司**（同一法人主体：法人代表 徐静姬、联系人 许玲玲、
电话 64040084、地址 上海市徐汇区虹桥路 268 号，台账两版逐字相同 —— 系更名，非新设、非合并）。

工单的「物业企业」字段自 2026-08-01 起改用新名，此前一律沿用旧名：

    · 旧名  上海中誉物业管理有限公司        全库 466 件（2024-06-18 ~ 2026-08-28）
    · 新名  上海中誉城市运营服务有限公司      全库  35 件（2026-08-01 ~ 2026-08-31）
    · 2026 年 1-8 月：旧名 187 + 新名 35 = **222 件**（2025 年同期 154 件，+44.2%）

**必须按同一主体合并统计**——企业名一旦不归并，同一家企业会被拆成两行，
各项计数（企业排名、分街镇企业榜、服务态度企业榜）会双双少算。

另外发现一处录入变体：底部抬升名单资产 `bottom_lift_communities.json` 内的企业名
含一个换行符（`上海中誉\n物业管理有限公司`），亦在此一并归一。

口径边界
--------
* 只做**更名归并**，不做近似名合并 —— 名称近似但未经确认的企业仍按其原文各自成行
  （见《口径细则》一：名称近似未精确匹配者出候选待人工确认，不自动纳入）。
* 小区层级的企业名（`community_linked_data.pkl`，源自《纳统小区 (2026 更新版)》）
  登记的本就是现用名，无需归并。
* 溯源列 `property_company_raw` 保留工单的原始填报值，不参与归并。
"""

import re

# 现用名 ← 历史填报名（含换行/全角空格等录入变体，统一按去空白后的名字比对）
CURRENT_NAME = "上海中誉城市运营服务有限公司"

COMPANY_RENAME = {
    "上海中誉物业管理有限公司": CURRENT_NAME,
}

# 该主体在工单数据中出现过的历史填报名（用于审计脚本识别陈旧写法）
LEGACY_NAMES = sorted(COMPANY_RENAME.keys())

_WS = re.compile(r"[\s\u3000\u00a0]+")


def canon_company(name) -> str:
    """企业名归并：先去掉全部空白字符（含换行/全角空格），再套用更名映射。"""
    if name is None:
        return ""
    s = _WS.sub("", str(name))
    return COMPANY_RENAME.get(s, s)


def canon_series(sr):
    """pandas Series 版本，保持索引不变。"""
    return sr.map(canon_company)
